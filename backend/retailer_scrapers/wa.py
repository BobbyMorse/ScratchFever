def _parse_inline_json(html: str) -> list[dict]:
    match = re.search(
        r"WaLottery\.SearchRetailersResults\.mapData\s*=\s*JSON\.parse\('({[^']+})'\)",
        html,
    )
    if not match:
        return []
    raw = match.group(1)
    # Unescape JS single-quoted string: \' → '
    raw = raw.replace("\\'", "'")
    try:
        data = json.loads(raw)
    except Exception:
        return []
    return data.get("Retailers") or []


def _parse_retailer(item: dict) -> dict | None:
    name = (item.get("RetailerName") or "").strip()
    if not name:
        return None
    store_id = item.get("StoreId") or item.get("RetailerNum")
    external_id = str(store_id).strip() if store_id else None
    if not external_id:
        return None
    lat = lng = None
    try:
        lat = float(item["RetailerLatitude"]) if item.get("RetailerLatitude") else None
        lng = float(item["RetailerLongitude"]) if item.get("RetailerLongitude") else None
    except (ValueError, TypeError):
        pass
    return {
        "external_id": external_id,
        "name": name,
        "address": (item.get("Address") or "").strip() or None,
        "city": (item.get("City") or "").strip() or None,
        "zip_code": (item.get("Zip") or "").strip() or None,
        "phone": (item.get("Phone") or "").strip() or None,
        "latitude": lat,
        "longitude": lng,
    }


def scrape_wa() -> list[dict]:
    import requests
    session = requests.Session()
    session.headers.update({
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
        "Referer": SEARCH_URL,
    })

    zips = list(dict.fromkeys(WA_ZIPS))
    logger.info("WA: scraping %d zip codes", len(zips))

    all_retailers: list[dict] = []
    seen_ids: set[str] = set()

    for i, zipcode in enumerate(zips):
        try:
            resp = session.post(
                SEARCH_URL,
                data={"txtZipCode": zipcode, "txtCity": ""},
                timeout=30,
            )
            resp.raise_for_status()
            items = _parse_inline_json(resp.text)
            new_count = 0
            for item in items:
                r = _parse_retailer(item)
                if r and r["external_id"] not in seen_ids:
                    seen_ids.add(r["external_id"])
                    all_retailers.append(r)
                    new_count += 1
        except Exception as e:
            logger.debug("WA: error on zip %s: %s", zipcode, e)
        time.sleep(0.25)

        if (i + 1) % 100 == 0:
            logger.info("WA: progress %d/%d zips, %d retailers", i + 1, len(zips), len(all_retailers))

    logger.info("WA: scraped %d unique retailers", len(all_retailers))
    return all_retailers


async def run(conn) -> int:
    import asyncio
    retailers = await asyncio.to_thread(scrape_wa)
    return await upsert_retailers(conn, "WA", retailers)
